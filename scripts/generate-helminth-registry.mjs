import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

import Database from 'better-sqlite3';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const dbPath = path.resolve(process.argv[2] ?? path.join(root, 'data/armory.db'));

function abilityPathBasename(uniqueName) {
  const i = uniqueName.lastIndexOf('/');
  return i >= 0 ? uniqueName.slice(i + 1) : uniqueName;
}

function helminthPathTier(uniqueName) {
  if (uniqueName.includes('/Abilities/')) return 0;
  if (uniqueName.includes('/PowersuitAbilities/')) return 1;
  return 2;
}

function dedupe(rows) {
  const byBasename = new Map();
  for (const row of rows) {
    const base = abilityPathBasename(row.unique_name);
    const list = byBasename.get(base);
    if (list) list.push(row);
    else byBasename.set(base, [row]);
  }
  const out = [];
  for (const list of byBasename.values()) {
    out.push(
      [...list].sort((a, b) => {
        const ta = helminthPathTier(a.unique_name);
        const tb = helminthPathTier(b.unique_name);
        if (ta !== tb) return ta - tb;
        return a.unique_name.localeCompare(b.unique_name);
      })[0],
    );
  }
  out.sort((a, b) => a.name.localeCompare(b.name));
  return out;
}

function slugFromName(name) {
  return name
    .replace(/'/g, '')
    .replace(/[^a-zA-Z0-9]+/g, ' ')
    .trim()
    .split(/\s+/)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase())
    .join('');
}

const db = new Database(dbPath, { readonly: true });
const rows = db
  .prepare(
    'SELECT unique_name, name FROM abilities WHERE is_helminth_extractable = 1 ORDER BY name',
  )
  .all();
db.close();

const bySlug = new Map();
for (const row of dedupe(rows)) {
  const slug = slugFromName(row.name);
  const entry = bySlug.get(slug) ?? { slug, name: row.name, de_paths: [] };
  entry.de_paths.push(row.unique_name);
  bySlug.set(slug, entry);
}

const entries = [...bySlug.values()].sort((a, b) => a.name.localeCompare(b.name));

const outPath = path.join(root, 'shared', 'helminthRegistry.generated.ts');
const body = `/** Auto-generated by scripts/generate-helminth-registry.mjs — do not edit by hand. */

export interface HelminthRegistryEntry {
  slug: string;
  name: string;
  armory_key: string;
  de_paths: readonly string[];
}

export const HELMINTH_REGISTRY_ENTRIES: readonly HelminthRegistryEntry[] = ${JSON.stringify(
  entries.map((e) => ({
    slug: e.slug,
    name: e.name,
    armory_key: `/Armory/Helminth/${e.slug}`,
    de_paths: e.de_paths,
  })),
  null,
  2,
)};
`;

fs.writeFileSync(outPath, body, 'utf8');
console.log(`Wrote ${entries.length} helminth entries to ${outPath}`);
