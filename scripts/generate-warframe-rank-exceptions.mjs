import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const sourcePath = path.join(root, 'scripts/data/warframe-rank-exceptions.json');
const outPath = path.join(root, 'shared/warframeRankExceptions.generated.ts');

function readSourceRows() {
  const raw = fs.readFileSync(sourcePath, 'utf8');
  const rows = JSON.parse(raw);
  if (!Array.isArray(rows)) {
    throw new Error('warframe-rank-exceptions.json must be an array');
  }

  const byUniqueName = {};
  for (const row of rows) {
    if (!row?.uniqueName || !row?.bonuses) {
      throw new Error(`Invalid row: ${JSON.stringify(row)}`);
    }
    if (byUniqueName[row.uniqueName]) {
      throw new Error(`Duplicate uniqueName: ${row.uniqueName}`);
    }
    byUniqueName[row.uniqueName] = row.bonuses;
  }

  return rows;
}

const rows = readSourceRows();
const byUniqueName = Object.fromEntries(rows.map((row) => [row.uniqueName, row.bonuses]));

const body = `/** Auto-generated by scripts/generate-warframe-rank-exceptions.mjs — do not edit by hand.
 * Source: scripts/data/warframe-rank-exceptions.json (wiki Warframe Rank Up Exceptions table).
 * @see https://wiki.warframe.com/w/Warframes#Leveling_Up
 */

import type { RankStatBonuses } from './equipmentRankStats.js';

export interface WarframeRankExceptionEntry {
  uniqueName: string;
  name: string;
  bonuses: RankStatBonuses;
}

export const WARFRAME_RANK_EXCEPTION_ENTRIES: readonly WarframeRankExceptionEntry[] = ${JSON.stringify(
  rows.map((row) => ({
    uniqueName: row.uniqueName,
    name: row.name,
    bonuses: row.bonuses,
  })),
  null,
  2,
)};

export const WARFRAME_RANK_EXCEPTIONS_BY_UNIQUE_NAME: Readonly<
  Record<string, RankStatBonuses>
> = ${JSON.stringify(byUniqueName, null, 2)};
`;

fs.writeFileSync(outPath, body, 'utf8');
console.log(`Wrote ${rows.length} entries to ${path.relative(root, outPath)}`);
